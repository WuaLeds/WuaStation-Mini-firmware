"""WuaStation-mini firmware as an ESPHome component.

The firmware core (lib/WuaStationCore: screens, internet data, sensors and
settings) runs inside this component, exactly as it does without Home
Assistant. ESPHome brings WiFi, the setup portal, the Home Assistant API, OTA
and logs; the platforms in this folder (sensor, light, text, select, switch,
button, event) mirror the station to Home Assistant.
"""

import gzip
import json
from pathlib import Path

import esphome.codegen as cg
from esphome.components import esp32, web_server_base
import esphome.config_validation as cv
from esphome.const import CONF_ID
from esphome.core import CORE
from esphome.helpers import write_file_if_changed

CODEOWNERS = ["@WuaLeds"]
DEPENDENCIES = ["esp32", "wifi"]
AUTO_LOAD = ["web_server_base", "json"]

COMPONENT_DIR = Path(__file__).resolve().parent
REPO_ROOT = COMPONENT_DIR.parents[1]
CORE_LIBRARY = REPO_ROOT / "lib" / "WuaStationCore"
SETTINGS_PAGE = REPO_ROOT / "web" / "settings.html"
# Same table as firmware 0.3 (min_spiffs): NVS stays at 0x9000, so an update
# keeps the settings and the WiFi network.
PARTITIONS = COMPONENT_DIR / "partitions.csv"

CONF_WUASTATION_ID = "wuastation_id"

wuastation_ns = cg.esphome_ns.namespace("wuastation")
WuaStation = wuastation_ns.class_("WuaStation", cg.Component)

CONFIG_SCHEMA = cv.Schema(
    {
        cv.GenerateID(): cv.declare_id(WuaStation),
        cv.GenerateID(web_server_base.CONF_WEB_SERVER_BASE_ID): cv.use_id(
            web_server_base.WebServerBase
        ),
    }
).extend(cv.COMPONENT_SCHEMA)


def _settings_page_header() -> str:
    """web/settings.html, gzipped, as a C array."""
    data = SETTINGS_PAGE.read_bytes()
    packed = gzip.compress(data, compresslevel=9, mtime=0)  # reproducible
    rows = [
        "    " + ", ".join(f"0x{b:02x}" for b in packed[i : i + 20]) + ","
        for i in range(0, len(packed), 20)
    ]
    return (
        "#pragma once\n\n"
        "// Generated by components/wuastation/__init__.py from web/settings.html.\n"
        f"// {len(data)} bytes of HTML, {len(packed)} bytes gzipped.\n\n"
        "#include <cstddef>\n#include <cstdint>\n\n"
        "namespace esphome::wuastation {\n"
        "static const uint8_t SETTINGS_PAGE_GZ[] = {\n" + "\n".join(rows) + "\n};\n"
        "static constexpr size_t SETTINGS_PAGE_GZ_SIZE = sizeof(SETTINGS_PAGE_GZ);\n"
        "}  // namespace esphome::wuastation\n"
    )


async def to_code(config):
    web = await cg.get_variable(config[web_server_base.CONF_WEB_SERVER_BASE_ID])
    var = cg.new_Pvariable(config[CONF_ID], web)
    await cg.register_component(var, config)

    # The firmware core, a PlatformIO library. Its dependencies (FastLED,
    # WuaDisplay-LMX, Adafruit GFX, BME280...) are listed in its library.json;
    # they are added here too because the component includes the core's
    # headers (ESPHome builds with the library finder off).
    cg.add_library("WuaStationCore", None, f"symlink://{CORE_LIBRARY.as_posix()}")
    manifest = json.loads((CORE_LIBRARY / "library.json").read_text(encoding="utf-8"))
    for dep in manifest.get("dependencies", []):
        version = dep.get("version")
        if version and "://" in version:
            cg.add_library(dep["name"], None, version)
        else:
            owner = dep.get("owner")
            cg.add_library(f"{owner}/{dep['name']}" if owner else dep["name"], version)

    # Arduino built-ins and ESP-IDF parts the core uses: ESPHome leaves out
    # whatever no component asks for.
    for library in ("Preferences", "Wire", "SPI"):
        cg.add_library(library, None)
    esp32.request_http_client()  # net/HttpJson (esp_http_client)
    esp32.require_certificate_bundle()  # HTTPS servers are verified
    # IDF drivers: RMT for the LEDs (FastLED), I2C for the sensors (Wire).
    for component in ("esp_driver_rmt", "esp_driver_gptimer", "esp_driver_i2c", "driver"):
        esp32.include_builtin_idf_component(component)
    # Third-party libraries declare their own dependencies (Adafruit GFX needs
    # Adafruit BusIO...): let PlatformIO follow them, honoring #if blocks, but
    # keep out the Arduino network and file system libraries some of them
    # mention (FastLED's SD card support...): ESPHome runs those parts.
    cg.add_platformio_option("lib_ldf_mode", "chain+")
    cg.add_platformio_option(
        "lib_ignore",
        ["WiFi", "Network", "AsyncUDP", "DNSServer", "Update", "Hash", "FS", "SD", "SD_MMC", "SPIFFS", "LittleFS"],
    )

    # WuaDisplay-LMX backend: LMX1p panel, data on GPIO5. Global flags, so the
    # library and the core see the same values.
    cg.add_build_flag("-DWUA_BOARD_LMX1P")
    cg.add_build_flag("-DLMX1P_LED_PIN=5")
    cg.add_build_flag("-DWUA_ENABLE_EFFECTS")
    # Core logs go to the ESPHome logger (wua_log_write in wuastation.cpp).
    cg.add_build_flag("-DWUA_LOG_HOOK")

    write_file_if_changed(
        Path(CORE.relative_src_path("wuastation_settings_page.h")),
        _settings_page_header(),
    )

    # Unless the configuration sets its own partitions.
    esp32.add_extra_build_file("partitions.csv", PARTITIONS)
