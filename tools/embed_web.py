"""PlatformIO pre-build script: embed the settings web page in the firmware.

web/settings.html is gzipped and written as a C array to
src/web/SettingsPageData.h (generated, git-ignored). The file is only
rewritten when its content changes, so unchanged pages do not trigger a
recompile. Also runnable by hand: python tools/embed_web.py
"""

import gzip
import os

try:
    Import("env")  # noqa: F821  (provided by PlatformIO/SCons)
    PROJECT_DIR = env.subst("$PROJECT_DIR")  # noqa: F821
except NameError:
    PROJECT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

SOURCE = os.path.join(PROJECT_DIR, "web", "settings.html")
TARGET = os.path.join(PROJECT_DIR, "src", "web", "SettingsPageData.h")


def build_header(data: bytes) -> str:
    packed = gzip.compress(data, compresslevel=9, mtime=0)  # mtime=0: reproducible output
    rows = []
    for i in range(0, len(packed), 20):
        rows.append("    " + ", ".join("0x%02x" % b for b in packed[i:i + 20]) + ",")
    return (
        "#pragma once\n\n"
        "// Generated by tools/embed_web.py from web/settings.html -- do not edit.\n"
        "// %d bytes of HTML, %d bytes gzipped.\n\n"
        "#include <Arduino.h>\n\n"
        "namespace WebAssets\n{\n"
        "    const uint8_t kSettingsPageGz[] PROGMEM = {\n%s\n    };\n"
        "    constexpr size_t kSettingsPageGzLength = sizeof(kSettingsPageGz);\n"
        "}\n" % (len(data), len(packed), "\n".join(rows))
    )


def main():
    with open(SOURCE, "rb") as f:
        header = build_header(f.read())
    old = None
    if os.path.exists(TARGET):
        with open(TARGET, "r", encoding="utf-8") as f:
            old = f.read()
    if old != header:
        os.makedirs(os.path.dirname(TARGET), exist_ok=True)
        with open(TARGET, "w", encoding="utf-8", newline="\n") as f:
            f.write(header)
        print("embed_web: wrote %s" % os.path.relpath(TARGET, PROJECT_DIR))


main()
